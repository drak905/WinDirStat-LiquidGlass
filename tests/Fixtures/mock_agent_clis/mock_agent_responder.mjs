function inferClassification(targetPath, overrideMode) {
  if (overrideMode === 'critical') return 'critical';
  if (overrideMode === 'caution') return 'caution';
  if (overrideMode === 'safe') return 'safe';

  const normalized = (targetPath || '').toLowerCase();
  if (
    normalized.includes('system32') ||
    normalized.includes('winsxs') ||
    normalized.includes('ntoskrnl') ||
    normalized.includes('kernel32') ||
    normalized.includes('program files') ||
    normalized.includes('bootmgr')
  ) {
    return 'critical';
  }
  if (
    normalized.includes('docker') ||
    normalized.includes('windowsfilter') ||
    normalized.includes('.vhdx') ||
    normalized.includes('downloads') ||
    normalized.includes('.git')
  ) {
    return 'caution';
  }
  return 'safe';
}

function extractTargetPath(promptText) {
  if (!promptText) {
    return 'C:\\Users\\Developer\\AppData\\Local\\Temp';
  }
  const winPathMatch = promptText.match(/[A-Za-z]:\\[^\s"'`<>|]+/);
  if (winPathMatch) {
    return winPathMatch[0].replace(/[.,;:!?)]+$/, '');
  }
  return 'C:\\Users\\Developer\\AppData\\Local\\Temp';
}

export function buildAgentResponse({
  provider = 'antigravity',
  prompt = '',
  mode = 'valid',
  targetPath = null,
} = {}) {
  const safeProvider = SUPPORTED_PROVIDERS.includes(provider) ? provider : 'antigravity';
  const resolvedPath = targetPath || extractTargetPath(prompt);
  const classification = inferClassification(resolvedPath, mode);

  const templates = {
    safe: {
      verdict: 'SAFE_TO_DELETE',
      risk_score: 8,
      reclaimable_bytes: 536_870_912,
      usage_value_assessment:
        `[${safeProvider}] "${resolvedPath}" contains ephemeral cache/build/temporary artifacts with low ongoing retention value. Moving it to the 7-Day Quarantine Vault preserves instant rollback safety while reclaiming disk space.`,
      recommended_action: 'QUARANTINE_7_DAYS',
      sources: SOURCE_BANK.safe,
    },
    caution: {
      verdict: 'SAFE_WITH_APP_CLOSED',
      risk_score: 48,
      reclaimable_bytes: 1_073_741_824,
      usage_value_assessment:
        `[${safeProvider}] "${resolvedPath}" may hold active container layers, downloaded installers, or repository history. Inspect active processes or place into 7-Day Quarantine before permanent deletion.`,
      recommended_action: 'ARCHIVE_OR_QUARANTINE_WITH_REVIEW',
      sources: SOURCE_BANK.caution,
    },
    critical: {
      verdict: 'KEEP_CRITICAL',
      risk_score: 98,
      reclaimable_bytes: 0,
      usage_value_assessment:
        `[${safeProvider}] "${resolvedPath}" is a protected Windows operating system location essential for boot integrity and runtime stability. Quarantine or deletion is strictly blocked.`,
      recommended_action: 'KEEP_PROTECTED',
      sources: SOURCE_BANK.critical,
    },
  };

  const chosen = templates[classification];
  const basePayload = {
    provider: safeProvider,
    model: PROVIDER_MODELS[safeProvider],
    target_path: resolvedPath,
    verdict: chosen.verdict,
    risk_score: chosen.risk_score,
    reclaimable_bytes: chosen.reclaimable_bytes,
    usage_value_assessment: chosen.usage_value_assessment,
    cross_checked_sources: chosen.sources.map((s) => ({ ...s })),
    recommended_action: chosen.recommended_action,
    generated_at: '2026-11-18T13:00:00Z',
  };

  if (mode === 'insufficient_sources') {
    basePayload.cross_checked_sources = basePayload.cross_checked_sources.slice(0, 2);
  } else if (mode === 'zero_sources') {
    basePayload.cross_checked_sources = [];
  } else if (mode === 'missing_fields') {
    delete basePayload.recommended_action;
    delete basePayload.usage_value_assessment;
    basePayload.risk_score = 150;
  }

  return basePayload;
}

function parseCliArgs(argv) {
  const opts = {
    provider: process.env.WDS_MOCK_PROVIDER || 'antigravity',
    mode: process.env.WDS_MOCK_AGENT_MODE || 'valid',
    stream: false,
    stdin: false,
    version: false,
    help: false,
    selfTest: false,
    servePort: null,
    targetPath: null,
    promptParts: [],
  };

  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === '--version' || arg === '-v') {
      opts.version = true;
    } else if (arg === '--help' || arg === '-h') {
      opts.help = true;
    } else if (arg === '--self-test') {
      opts.selfTest = true;
    } else if (arg === '--stream') {
      opts.stream = true;
    } else if (arg === '--stdin') {
      opts.stdin = true;
    } else if (arg === '--provider' && i + 1 < argv.length) {
      opts.provider = argv[++i];
    } else if (arg === '--mode' && i + 1 < argv.length) {
      opts.mode = argv[++i];
    } else if (arg === '--target' && i + 1 < argv.length) {
      opts.targetPath = argv[++i];
    } else if (arg === '--prompt-file' && i + 1 < argv.length) {
      const promptFile = argv[++i];
      if (fs.existsSync(promptFile)) {
        opts.promptParts.push(fs.readFileSync(promptFile, 'utf8'));
      }
    } else if (arg === '--serve' && i + 1 < argv.length) {
      opts.servePort = Number.parseInt(argv[++i], 10);
    } else if ((arg === '-p' || arg === '--prompt' || arg === 'run' || arg === 'exec') && i + 1 < argv.length) {
      if (arg === 'run' || arg === 'exec') continue;
      opts.promptParts.push(argv[++i]);
    } else if (arg === '--output-format' && i + 1 < argv.length) {
      const fmt = argv[++i];
      if (fmt === 'stream-json' || fmt === 'ndjson') opts.stream = true;
    } else if (!arg.startsWith('-')) {
      opts.promptParts.push(arg);
    }
  }
  return opts;
}

function readStdinSyncIfPiped() {
  try {
    if (!process.stdin.isTTY) {
      return fs.readFileSync(0, 'utf8').trim();
    }
  } catch {
    // Ignore non-readable stdin in detached shells
  }
  return '';
}

function runSelfTest() {
  for (const provider of SUPPORTED_PROVIDERS) {
    const valid = buildAgentResponse({
      provider,
      prompt: 'Evaluate C:\\Users\\Developer\\AppData\\Local\\Temp',
      mode: 'valid',
    });
    if (valid.provider !== provider) throw new Error(`Provider mismatch for ${provider}`);
    if (valid.verdict !== 'SAFE_TO_DELETE') throw new Error(`Expected SAFE_TO_DELETE for ${provider}`);
    if (!Array.isArray(valid.cross_checked_sources) || valid.cross_checked_sources.length < 3) {
      throw new Error(`Expected >= 3 sources for ${provider}`);
    }

    const critical = buildAgentResponse({
      provider,
      prompt: 'Evaluate C:\\Windows\\System32',
      mode: 'valid',
    });
    if (critical.verdict !== 'KEEP_CRITICAL' || critical.risk_score < 90) {
      throw new Error(`Expected KEEP_CRITICAL for System32 on ${provider}`);
    }

    const insufficient = buildAgentResponse({
      provider,
      prompt: 'Evaluate C:\\Users\\Developer\\AppData\\Local\\Temp',
      mode: 'insufficient_sources',
    });
    if (insufficient.cross_checked_sources.length >= 3) {
      throw new Error(`Expected < 3 sources in insufficient_sources mode on ${provider}`);
    }
  }

  console.log(
    JSON.stringify(
      {
        status: 'PASS',
        providersTested: SUPPORTED_PROVIDERS,
        modesVerified: ['valid', 'critical', 'caution', 'insufficient_sources', 'zero_sources', 'missing_fields'],
      },
      null,
      2
    )
  );
}

function startMockHttpServer(port) {
  const server = http.createServer((req, res) => {
    res.setHeader('Access-Control-Allow-Origin', '*');
    res.setHeader('Access-Control-Allow-Headers', 'Content-Type');
    res.setHeader('Access-Control-Allow-Methods', 'GET, POST, OPTIONS');

    if (req.method === 'OPTIONS') {
      res.writeHead(204);
      res.end();
      return;
    }

    if (req.url === '/health') {
      res.writeHead(200, { 'Content-Type': 'application/json' });
      res.end(JSON.stringify({ status: 'ok', providers: SUPPORTED_PROVIDERS }));
      return;
    }

    if (req.method === 'POST' && req.url?.startsWith('/analyze')) {
      let body = '';
      req.on('data', (chunk) => {
        body += chunk;
      });
      req.on('end', () => {
        let parsed = {};
        try {
          parsed = body ? JSON.parse(body) : {};
        } catch {
          res.writeHead(400, { 'Content-Type': 'application/json' });
          res.end(JSON.stringify({ error: 'Invalid JSON request body' }));
          return;
        }
        const payload = buildAgentResponse({
          provider: parsed.provider || 'antigravity',
          prompt: parsed.prompt || '',
          mode: parsed.mode || 'valid',
          targetPath: parsed.targetPath || null,
        });
        res.writeHead(200, { 'Content-Type': 'application/json' });
        res.end(JSON.stringify(payload));
      });
      return;
    }

    res.writeHead(404, { 'Content-Type': 'application/json' });
    res.end(JSON.stringify({ error: 'Not Found' }));
  });

  server.listen(port, '127.0.0.1', () => {
    console.log(`[MockAgentServer] Listening on http://127.0.0.1:${port}`);
  });
}

function main() {
  const opts = parseCliArgs(process.argv.slice(2));

  if (opts.version) {
    console.log(`${opts.provider}-mock 1.0.0`);
    return;
  }

  if (opts.help) {
    console.log(`Mock Agent CLI (${opts.provider}) - WinDirStat Liquid Glass QA Fixture`);
    return;
  }

  if (opts.selfTest) {
    runSelfTest();
    return;
  }

  if (opts.servePort !== null && !Number.isNaN(opts.servePort)) {
    startMockHttpServer(opts.servePort);
    return;
  }

  if (opts.mode === 'cli_error') {
    console.error(`[${opts.provider}] simulated CLI process failure`);
    process.exit(1);
  }

  if (opts.mode === 'malformed_json') {
    process.stdout.write('{"verdict":"SAFE_TO_DELETE","cross_checked_sources":[{"url":"https://broken');
    return;
  }

  const stdinPrompt = opts.stdin && opts.promptParts.length === 0 && !opts.targetPath
    ? readStdinSyncIfPiped()
    : '';
  const prompt = opts.promptParts.join(' ') || stdinPrompt;
  const payload = buildAgentResponse({
    provider: opts.provider,
    prompt,
    mode: opts.mode,
    targetPath: opts.targetPath,
  });

  if (opts.stream || opts.mode === 'stream') {
    const words = payload.usage_value_assessment.split(' ');
    const midpoint = Math.ceil(words.length / 2);
    const chunk1 = words.slice(0, midpoint).join(' ') + ' ';
    const chunk2 = words.slice(midpoint).join(' ');
    process.stdout.write(JSON.stringify({ event: 'chunk', provider: payload.provider, delta: chunk1 }) + '\n');
    process.stdout.write(JSON.stringify({ event: 'chunk', provider: payload.provider, delta: chunk2 }) + '\n');
    process.stdout.write(JSON.stringify({ event: 'final', data: payload }) + '\n');
    return;
  }

  process.stdout.write(JSON.stringify(payload, null, 2) + '\n');
}

const isEntrypoint = process.argv[1] && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url));
if (isEntrypoint) {
  main();
}
