/**
 * Cross-Platform Mock Agent CLI Responder & Optional Mock Server
 *
 * Simulates the 5 pluggable Agent CLIs (`antigravity`, `kiro`, `claude`, `codex`, `opencode`)
 * for Tier 2 Rust integration tests (`agent_cli_integration`) and Tier 4 Playwright E2E tests.
 *
 * Modes (via --mode or WDS_MOCK_AGENT_MODE):
 *   - valid (default): returns valid structured JSON with >= 3 authoritative source URLs
 *   - insufficient_sources: returns < 3 source URLs (2 URLs) to test strict rejection gate
 *   - zero_sources: returns 0 source URLs (`cross_checked_sources: []`)
 *   - missing_fields: omits required schema keys (`recommended_action`, `risk_score`)
 *   - malformed_json: prints truncated invalid JSON to stdout
 *   - cli_error: exits with non-zero code (1) and stderr message
 *   - stream: emits newline-delimited JSON streaming deltas followed by final payload
 */

